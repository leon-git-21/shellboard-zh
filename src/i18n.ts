export function translate(language: Language, text: string): string {
  return language === "zh-CN" ? chinese.get(text) ?? text : text;
}

export function nativeMenuLabels(language: Language): Record<string, string> {
  return language === "zh-CN" ? Object.fromEntries(chinese) : {};
}

export function useI18n() {
  const language = useAppStore((state) => state.settings.language);
  const t = useCallback((text: string) => translate(language, text), [language]);
  return { language, t };
}
